#!/usr/bin/env node
/**
 * Builds src/lib/gym/nevoFoods.data.ts from the NEVO online dataset (RIVM,
 * the Dutch food composition table) — unpackaged food with no barcode or
 * label: fruit, vegetables, potatoes, grains, bread, eggs, meat, fish,
 * dairy, nuts, legumes, fats and oils, and drinks (a beer at a bar or a
 * glass of wine has no label either).
 *
 *   node scripts/build-nevo-foods.mjs path/to/NEVO2025_v9.0.csv
 *
 * The raw dataset is not committed (see .gitignore): download it from
 * rivm.nl, accepting RIVM's conditions of use, and point this script at the
 * main CSV (`NEVO<year>_v<version>.csv`, `|`-separated, UTF-8, decimal
 * commas). RIVM asks users to move to each new NEVO version when it's
 * released — re-run this with the new file and update NEVO_VERSION below
 * and the references in sources.ts / i18n.ts.
 *
 * Conditions of use this script follows: values are copied unchanged (only
 * parsed from "1,8" to 1.8), whole food groups are taken as published
 * rather than filtered by hand, and NEVO's own names and synonyms are kept
 * as they are. Salt isn't in NEVO; the app derives it from sodium at
 * runtime (nevoFoods.ts), an addition marked as such in the UI.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const NEVO_VERSION = "2025/9.0";

/** Food groups taken whole (Dutch group names, as in the dataset). Left out:
 *  sweets, sauces, snacks, spreads, mixed dishes, soups and special
 *  nutrition, which come with a label or aren't single foods. Drinks are in
 *  (alcoholic and non-alcoholic) since a beer at a bar or a glass of wine
 *  has no label; alcohol.ts uses the beers and wines. */
const GROUPS = [
  "Fruit",
  "Groente",
  "Aardappelen en knolgewassen",
  "Graanproducten en meelsoorten",
  "Brood",
  "Eieren",
  "Vlees en gevogelte",
  "Vis, schaal- en schelpdieren",
  "Melk en melkproducten",
  "Kaas",
  "Noten en zaden",
  "Peulvruchten",
  "Vetten en oliën",
  "Alcoholische dranken",
  "Niet-alcoholische dranken",
];

const COLUMNS = {
  group: "Voedingsmiddelgroep",
  groupEn: "Food group",
  code: "NEVO-code",
  nl: "Voedingsmiddelnaam/Dutch food name",
  en: "Engelse naam/Food name",
  synonyms: "Synoniem",
  quantity: "Hoeveelheid/Quantity",
  kcal: "ENERCC (kcal)",
  protein: "PROT (g)",
  carbs: "CHO (g)",
  fat: "FAT (g)",
  fiber: "FIBT (g)",
  sodium: "NA (mg)",
  alcohol: "ALC (g)",
};

/** Parses NEVO's `|`-separated, double-quoted CSV. */
function parse(text) {
  const lines = text
    .replace(/^\uFEFF/, "")
    .split(/\r?\n/)
    .filter((l) => l.length);
  const split = (line) => line.split("|").map((c) => c.replace(/^"(.*)"$/, "$1").trim());
  const header = split(lines[0]);
  return lines.slice(1).map((line) => {
    const cells = split(line);
    return Object.fromEntries(header.map((h, i) => [h, cells[i] ?? ""]));
  });
}

/** "1,8" → 1.8; empty → null (not in the dataset — never guessed). */
function num(value) {
  const v = value.trim();
  if (!v) return null;
  const n = Number(v.replace(",", "."));
  if (!Number.isFinite(n)) throw new Error(`Not a number: ${value}`);
  return n;
}

const file = process.argv[2];
if (!file) {
  console.error("Usage: node scripts/build-nevo-foods.mjs path/to/NEVO<year>_v<version>.csv");
  process.exit(1);
}

const rows = parse(readFileSync(file, "utf8"));
for (const key of Object.values(COLUMNS)) {
  if (!(key in rows[0])) throw new Error(`Column missing from the NEVO file: ${key}`);
}

const groups = [];
const foods = [];
for (const r of rows) {
  const gi = GROUPS.indexOf(r[COLUMNS.group]);
  if (gi < 0) continue;
  if (r[COLUMNS.quantity] !== "per 100g")
    throw new Error(`Unexpected basis: ${r[COLUMNS.quantity]}`);
  groups[gi] = [r[COLUMNS.group], r[COLUMNS.groupEn]];
  const kcal = num(r[COLUMNS.kcal]);
  const protein = num(r[COLUMNS.protein]);
  const carbs = num(r[COLUMNS.carbs]);
  const fat = num(r[COLUMNS.fat]);
  const fiber = num(r[COLUMNS.fiber]);
  if ([kcal, protein, carbs, fat, fiber].some((v) => v === null)) {
    throw new Error(`Missing energy or macronutrient for NEVO code ${r[COLUMNS.code]}`);
  }
  const alcohol = num(r[COLUMNS.alcohol]);
  foods.push([
    Number(r[COLUMNS.code]),
    r[COLUMNS.nl],
    r[COLUMNS.en],
    r[COLUMNS.synonyms],
    gi,
    kcal,
    protein,
    carbs,
    fat,
    fiber,
    num(r[COLUMNS.sodium]),
    // Alcohol g per 100 g, only where NEVO has a value above 0.
    ...(alcohol ? [alcohol] : []),
  ]);
}
foods.sort((a, b) => a[0] - b[0]);

const out = `// Generated by scripts/build-nevo-foods.mjs — do not edit by hand.
// Based on data from NEVO online version ${NEVO_VERSION}, RIVM, Bilthoven.
// Values are copied unchanged from the dataset (conditions of use: see
// scripts/build-nevo-foods.mjs and CLAUDE.md "Unpackaged food (NEVO)").

export const NEVO_VERSION = ${JSON.stringify(NEVO_VERSION)};

/** [Dutch, English] food group names, indexed by NevoRow's group field. */
export const NEVO_GROUPS: [string, string][] = ${JSON.stringify(groups)};

/** [code, Dutch name, English name, Dutch synonyms ("/"-separated), group,
 *  kcal, protein g, available carbohydrate g, fat g, fibre g, sodium mg
 *  (null when NEVO has no value), alcohol g (only present when above 0)] —
 *  all per 100 g. */
export type NevoRow = [
  number,
  string,
  string,
  string,
  number,
  number,
  number,
  number,
  number,
  number,
  number | null,
  number?,
];

export const NEVO_FOODS: NevoRow[] = [
${foods.map((f) => "  " + JSON.stringify(f)).join(",\n")},
];
`;

const target = join(dirname(fileURLToPath(import.meta.url)), "../src/lib/gym/nevoFoods.data.ts");
writeFileSync(target, out);
console.log(`Wrote ${foods.length} foods from ${groups.length} groups to ${target}`);
